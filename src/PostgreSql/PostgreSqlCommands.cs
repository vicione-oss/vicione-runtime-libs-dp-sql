using System.Collections.Generic;
using System.Data.Common;
using System.Globalization;
using System.Linq;
using System.Text;

namespace ViciOne.Suite.DataPort;

internal static class PostgreSqlCommands
{
    internal const string SelectAllSchemasWithInformation = """
    SELECT 
        s.schema_name AS schema,
        t.table_name AS table,
        c.column_name AS column,
        c.data_type AS type,
        CAST (CASE WHEN ccu.column_name = c.column_name THEN true ELSE false END AS boolean) AS primary_key,
        CAST (CASE WHEN c.is_nullable = 'YES' THEN false ELSE true END AS boolean) AS not_null,
        CAST (CASE WHEN c.is_identity = 'YES' THEN true ELSE false END AS boolean) AS auto_increment
    FROM information_schema.schemata AS s
        LEFT JOIN information_schema.tables AS t ON s.schema_name = t.table_schema
        LEFT JOIN information_schema.columns AS c  ON c.table_name = t.table_name AND c.table_schema = t.table_schema
    	LEFT JOIN information_schema.table_constraints AS tc  ON tc.table_name = t.table_name AND tc.table_schema = t.table_schema AND tc.constraint_type = 'PRIMARY KEY'
    	LEFT JOIN information_schema.constraint_column_usage AS ccu  ON ccu.table_name = t.table_name AND ccu.table_schema = t.table_schema AND tc.constraint_name = ccu.constraint_name
        WHERE s.schema_name NOT IN ('pg_catalog', 'pg_toast', 'information_schema')
    """;

    internal static SchemaInfo ReadSchemaInfo(DbDataReader reader)
        => new(
            reader.GetFieldValue<string>(0),
            reader.IsDBNull(1) ? null : reader.GetFieldValue<string>(1),
            reader.IsDBNull(2) ? null : reader.GetFieldValue<string>(2),
            reader.IsDBNull(3) ? null : reader.GetFieldValue<string>(3),
            reader.GetFieldValue<bool>(4),
            reader.GetFieldValue<bool>(5),
            reader.GetFieldValue<bool>(6));

    private static string ComposeTableName(string schema, string table)
        => $"{IdentifierQuoter.QuoteForAnsiSql(schema)}.{IdentifierQuoter.QuoteForAnsiSql(table)}";

    internal static string ComposeCreateStructureCommandText(IReadOnlyCollection<Database> missingSchemas, IReadOnlyCollection<Database> missingTables)
    {
        StringBuilder commandText = new();

        foreach (var database in missingSchemas)
        {
            foreach (var schema in database.Schemas)
                commandText.AppendLine(ComposeCreateSchemaCommandText(schema));
        }

        foreach (var database in missingTables)
        {
            foreach (var schema in database.Schemas)
            {
                foreach (var table in schema.Tables)
                    commandText.AppendLine(ComposeCreateTableCommandText(schema, table));
            }
        }

        return commandText.ToString().TrimEnd();
    }

    internal static string ComposeCreateSchemaCommandText(Schema schema)
        => $"CREATE SCHEMA {IdentifierQuoter.QuoteForAnsiSql(schema.Name)};";

    internal static string ComposeCreateTableCommandText(Schema schema, Table table)
    {
        StringBuilder command = new();

        command.AppendFormat(CultureInfo.InvariantCulture, "CREATE TABLE {0} (", ComposeTableName(schema.Name, table.Name));
        command.AppendLine();

        var last = table.Columns.Count - 1;
        var i = 0;

        foreach (var column in table.Columns)
        {
            command.Append(CultureInfo.InvariantCulture, $"{IdentifierQuoter.QuoteForAnsiSql(column.Name)} {column.Type}");

            if (column.AutoIncrement)
                command.Append(" GENERATED BY DEFAULT AS IDENTITY");
            if (column.PrimaryKey)
                command.Append(" PRIMARY KEY");
            if (column.NotNull)
                command.Append(" NOT NULL");

            if (i != last)
                command.AppendLine(",");

            i++;
        }

        command.Append(");");

        return command.ToString();
    }

    internal static string ComposeCopyCommand(string table, string schema, IEnumerable<ColumnInfo> columnInfos)
    {
        StringBuilder command = new();

        command.Append("COPY ");
        command.Append(CultureInfo.InvariantCulture, $"{IdentifierQuoter.QuoteForAnsiSql(schema)}.{IdentifierQuoter.QuoteForAnsiSql(table)}");
        command.Append(" (");
        command.AppendJoin(',', columnInfos.Select(c => IdentifierQuoter.QuoteForAnsiSql(c.Name)));
        command.Append(") FROM STDIN (FORMAT BINARY);");

        return command.ToString();
    }
}
